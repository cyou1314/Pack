import Foundation
import CryptoKit
import Security

public enum AgentEnrollmentError: Error, Equatable {
    case invalidIdentity
    case randomFailure
    case receiptMismatch
    case credentialInvalid
    case alreadyEnrolling
}

public struct AgentHubInstance: Codable, Equatable, Sendable {
    public let instanceId: String
    enum CodingKeys: String, CodingKey { case instanceId = "instance_id" }
    public init(instanceId: String) { self.instanceId = instanceId }
    public var isValid: Bool {
        instanceId.range(of: "^[a-f0-9]{32}$", options: .regularExpression) != nil
    }
}

public struct AgentExecutorProvisionRequest: Codable, Equatable, Sendable {
    public let instanceId: String
    public let accountRef: String
    public let provider: String
    public let accessKind: String
    public let tokenSHA256: String
    enum CodingKeys: String, CodingKey {
        case instanceId = "instance_id", accountRef = "account_ref", provider
        case accessKind = "access_kind", tokenSHA256 = "token_sha256"
    }
}

public struct AgentExecutorProvisionReceipt: Codable, Equatable, Sendable {
    public let instanceId: String
    public let accountRef: String
    public let provider: String
    public let accessKind: String
    public let memberId: Int
    public let created: Bool
    enum CodingKeys: String, CodingKey {
        case instanceId = "instance_id", accountRef = "account_ref", provider
        case accessKind = "access_kind", memberId = "member_id", created
    }
    public init(instanceId:String, accountRef:String, provider:String, accessKind:String, memberId:Int, created:Bool) {
        self.instanceId = instanceId; self.accountRef = accountRef; self.provider = provider
        self.accessKind = accessKind; self.memberId = memberId; self.created = created
    }
    public func matches(_ request: AgentExecutorProvisionRequest) -> Bool {
        memberId > 0 && instanceId == request.instanceId && accountRef == request.accountRef &&
        provider == request.provider && accessKind == request.accessKind
    }
}

/// Trusted host boundary only. The owner channel receives a hash; the
/// verification channel authenticates using the dedicated token. UI callers
/// get metadata, never a bearer token. No automatic network retry.
public actor AgentExecutorEnrollment {
    private let backend: any AgentSecretBackend
    private var active: Set<String> = []

    public init() {
        backend = AgentKeychainBackend(service:"com.cyou.pack.executor-token.v1")
    }
    public init(backend: any AgentSecretBackend) { self.backend = backend }

    private func account(instance: AgentHubInstance, destination: AgentExecutionDestination) throws -> String {
        guard instance.isValid, let uuid = UUID(uuidString:destination.accountRef),
              uuid.uuidString.lowercased() == destination.accountRef,
              ["openai":"api","gemini-api":"api","volcengine":"api",
               "chatgpt":"native","gemini":"native","doubao":"native"][destination.provider] == destination.accessKind
        else { throw AgentEnrollmentError.invalidIdentity }
        return instance.instanceId + ":" + destination.provider + ":" + destination.accountRef
    }

    private func validateToken(_ data: Data) throws -> String {
        guard let token = String(data:data,encoding:.utf8),
              token.range(of:"^pk-mem-[a-f0-9]{64}$",options:.regularExpression) != nil
        else { throw AgentEnrollmentError.credentialInvalid }
        return token
    }

    private func token(account: String) async throws -> String {
        do { return try validateToken(await backend.read(account:account)) }
        catch AgentVaultError.missing {
            var bytes = [UInt8](repeating:0,count:32)
            let status = bytes.withUnsafeMutableBytes {
                SecRandomCopyBytes(kSecRandomDefault,$0.count,$0.baseAddress!)
            }
            guard status == errSecSuccess else { throw AgentEnrollmentError.randomFailure }
            let value = "pk-mem-" + bytes.map { String(format:"%02x",$0) }.joined()
            do { try await backend.insert(account:account,secret:Data(value.utf8)) }
            catch AgentVaultError.duplicate {
                // A cooperating concurrent process may have saved the key.
                // Never replace it; reload the one already persisted.
                return try validateToken(await backend.read(account:account))
            }
            return try validateToken(await backend.read(account:account))
        }
    }

    /// Read-only authentication of an existing token. Missing credentials
    /// are never regenerated by a status check.
    public func verifyExisting(instance: AgentHubInstance, destination: AgentExecutionDestination,
                               memberId: Int,
                               verify: @Sendable (String, AgentHubInstance, AgentExecutionDestination, Int) async throws -> Bool)
        async throws -> Bool {
        guard memberId > 0, !Task.isCancelled else { throw AgentEnrollmentError.invalidIdentity }
        let key = try account(instance:instance,destination:destination)
        let secret = try validateToken(await backend.read(account:key))
        return try await verify(secret,instance,destination,memberId) && !Task.isCancelled
    }

    public func enroll(instance: AgentHubInstance, destination: AgentExecutionDestination,
                       provision: @Sendable (AgentExecutorProvisionRequest) async throws -> AgentExecutorProvisionReceipt,
                       verify: @Sendable (String, AgentHubInstance, AgentExecutionDestination, Int) async throws -> Bool)
        async throws -> AgentExecutorProvisionReceipt {
        let key = try account(instance:instance,destination:destination)
        guard active.insert(key).inserted else { throw AgentEnrollmentError.alreadyEnrolling }
        defer { active.remove(key) }
        guard !Task.isCancelled else { throw CancellationError() }
        // Persist first. A crash or unknown response can reuse the exact
        // token for this database/profile without generating a new identity.
        let secret = try await token(account:key)
        let digest = SHA256.hash(data:Data(secret.utf8)).map { String(format:"%02x",$0) }.joined()
        let request = AgentExecutorProvisionRequest(instanceId:instance.instanceId,
            accountRef:destination.accountRef,provider:destination.provider,
            accessKind:destination.accessKind,tokenSHA256:digest)
        guard !Task.isCancelled else { throw CancellationError() }
        let receipt = try await provision(request)
        guard receipt.matches(request), !Task.isCancelled else { throw AgentEnrollmentError.receiptMismatch }
        guard try await verify(secret,instance,destination,receipt.memberId), !Task.isCancelled else {
            throw AgentEnrollmentError.receiptMismatch
        }
        return receipt
    }
}


public struct AgentExecutorIdentity: Codable, Equatable, Sendable {
    public let instanceId: String
    public let accountRef: String
    public let provider: String
    public let accessKind: String
    public let memberId: Int
    enum CodingKeys: String, CodingKey {
        case instanceId = "instance_id", accountRef = "account_ref", provider
        case accessKind = "access_kind", memberId = "member_id"
    }
    public func matches(instance: AgentHubInstance, destination: AgentExecutionDestination, memberId: Int) -> Bool {
        memberId > 0 && self.memberId == memberId && instanceId == instance.instanceId &&
        accountRef == destination.accountRef && provider == destination.provider && accessKind == destination.accessKind
    }
}
public struct AgentExecutorBindingStatus: Decodable, Sendable {
    public let instanceId: String
    public let accountRef: String
    public let state: String
    public let memberId: Int?
    public let provider: String?
    public let accessKind: String?
    enum CodingKeys: String, CodingKey {
        case instanceId = "instance_id", accountRef = "account_ref", state, provider
        case accessKind = "access_kind", memberId = "member_id"
    }
    public func matches(instance: AgentHubInstance, destination: AgentExecutionDestination) -> Bool {
        guard instanceId == instance.instanceId, accountRef == destination.accountRef else { return false }
        if state == "unbound" { return memberId == nil && provider == nil && accessKind == nil }
        return ["bound","revoked","unavailable"].contains(state) && (memberId ?? 0)>0 &&
            provider == destination.provider && accessKind == destination.accessKind
    }
}
public struct AgentExecutorRevokeReceipt: Decodable, Sendable {
    public let instanceId: String
    public let accountRef: String
    public let memberId: Int
    public let revoked: Bool
    enum CodingKeys: String, CodingKey {
        case instanceId = "instance_id", accountRef = "account_ref", memberId = "member_id", revoked
    }
}
